function escapeXml(value) {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");
}

const sourceBuffer = await fs.readFile(sourcePath);
const zip = await JSZip.loadAsync(sourceBuffer);
let totalReplacements = 0;

for (const name of Object.keys(zip.files)) {
  if (!/^ppt\/(slides|slideMasters|slideLayouts)\/.+\.xml$/.test(name)) continue;
  let xml = await zip.file(name).async("string");
  for (const [from, to] of replacements) {
    if (from === to) continue;
    const escapedFrom = escapeXml(from);
    const escapedTo = escapeXml(to);
    const occurrences = xml.split(escapedFrom).length - 1;
    if (occurrences > 0) {
      xml = xml.split(escapedFrom).join(escapedTo);
      totalReplacements += occurrences;
    }
  }
  zip.file(name, xml);
}

await fs.mkdir(path.dirname(draftPath), { recursive: true });
const output = await zip.generateAsync({ type: "nodebuffer" });
await fs.writeFile(draftPath, output);
console.log(`Wrote ${draftPath}`);
console.log(`Applied ${totalReplacements} text replacements`);
